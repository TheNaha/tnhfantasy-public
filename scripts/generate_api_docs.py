#!/usr/bin/env python3
"""Write the generated route index in `docs/api.md` from the live OpenAPI schema.

`docs/api.md` is the only description of the HTTP surface a human reads, and it
had drifted to covering 131 of 249 paths with no test noticing — for three audits.
Hand-maintaining it does not scale: the moment a route is added, the document is
wrong again and nothing fails.

So the exhaustive part is generated, and the hand-written part stays prose about
behaviour. `backend_v2/tests/test_api_docs_contract.py` then checks both
directions — every path the document names must exist, and coverage must not fall
back below 65% — so the generated section cannot silently rot either.

Run after changing any router:

    cd backend_v2 && .venv/bin/python ../scripts/generate_api_docs.py

Idempotent: it replaces everything between the BEGIN/END markers and nothing else.
Paths already documented in the hand-written prose are still listed, because the
index is a reference, not a narrative — duplication with prose is fine here and
the drift check only cares that every *documented* path exists.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "api.md"

BEGIN = "<!-- BEGIN GENERATED ROUTE INDEX -->"
END = "<!-- END GENERATED ROUTE INDEX -->"

# Group prefixes in the order a reader wants them; anything else lands in "Other".
GROUPS: list[tuple[str, str]] = [
    ("/api/v2/characters", "Characters"),
    ("/api/v2/chats", "Chats"),
    ("/api/v2/stories", "Stories"),
    ("/api/v2/worlds", "Worlds"),
    ("/api/v2/world-vault", "World Vault (aggregates)"),
    ("/api/v2/lorebooks", "Lorebooks"),
    ("/api/v2/locations", "Locations"),
    ("/api/v2/sessions", "Sessions"),
    ("/api/v2/timeline", "Timeline"),
    ("/api/v2/memories", "Memories"),
    ("/api/v2/collections", "Collections"),
    ("/api/v2/gallery", "Gallery"),
    ("/api/v2/assets", "Assets"),
    ("/api/v2/models", "Models"),
    ("/api/v2/providers", "Providers"),
    ("/api/v2/voices", "Voices"),
    ("/api/v2/scenarios", "Scenarios"),
    ("/api/v2/prompts", "Prompts (v2)"),
    ("/api/v2/generate", "Generation (v2)"),
    ("/api/v2/upload", "Upload (v2)"),
    ("/api/jobs", "Jobs"),
    ("/api/files", "Files"),
    ("/api/settings", "Settings"),
    ("/api/statistics", "Statistics"),
    ("/api/prompts", "Prompts"),
    ("/api/generate", "Generation"),
    ("/api/nodes", "Nodes"),
    ("/api/upload", "Upload"),
]

# A summary for the ones a reader would otherwise have to guess at. Keyed on the
# exact path, because a substring match here would mislabel neighbours.
SUMMARIES: dict[str, str] = {
    "/api/v2/stories/{story_id}/chapters": "List a story's chapters.",
    "/api/v2/stories/{story_id}/chapters/{chapter_id}": "Read or replace one chapter.",
    "/api/v2/stories/{story_id}/chapters/reorder": "Reorder the chapter list.",
    "/api/v2/stories/{story_id}/publish": "Publish a story to a token URL.",
    "/api/v2/sessions": "List generation sessions.",
    "/api/v2/memories/reindex": "Re-embed every memory. Expensive.",
    "/api/v2/models/cleanup-orphaned": "Delete assets whose model no longer exists.",
    "/api/v2/models/sync-progress": "Reconcile a batch of models' install progress.",
    "/api/jobs/reconcile-chat-replies": "Rewrite chat replies against their jobs.",
    "/api/jobs/acknowledge": "Acknowledge a terminal job so it stops nagging.",
}

ORDER = {"get": 0, "post": 1, "put": 2, "patch": 3, "delete": 4}


def load_paths() -> dict[str, dict]:
    sys.path.insert(0, str(ROOT / "backend_v2"))
    import logging

    logging.disable(logging.CRITICAL)
    from api.main import app

    return app.openapi()["paths"]


def group_for(path: str) -> str:
    for prefix, label in GROUPS:
        if path.startswith(prefix):
            return label
    return "Other"


def render(paths: dict[str, dict]) -> str:
    lines: list[str] = [
        BEGIN,
        "",
        "<!-- Generated by scripts/generate_api_docs.py. Do not edit by hand. -->",
        "",
        f"The live surface is **{len(paths)} paths / "
        f"{sum(len(v) for v in paths.values())} operations**. Everything below is",
        "derived from `app.openapi()`, so it cannot name a route that does not exist.",
        "",
    ]

    grouped: dict[str, list[str]] = {}
    for path in sorted(paths):
        grouped.setdefault(group_for(path), []).append(path)

    for label in [g[1] for g in GROUPS] + ["Other"]:
        members = grouped.get(label)
        if not members:
            continue
        lines.append(f"### {label}")
        lines.append("")
        for path in members:
            methods = sorted(paths[path], key=lambda m: ORDER.get(m, 99))
            verbs = ", ".join(f"`{m.upper()}`" for m in methods)
            note = SUMMARIES.get(path)
            lines.append(f"- {verbs} `{path}`" + (f" — {note}" if note else ""))
        lines.append("")

    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    paths = load_paths()
    block = render(paths)

    text = DOC.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        # First run: append the section rather than failing, so adding the
        # generator is never a two-step change.
        text = text.rstrip() + "\n\n---\n\n## Route index (generated)\n\n" + block + "\n"
    else:
        text = re.sub(
            re.escape(BEGIN) + r".*?" + re.escape(END),
            block,
            text,
            flags=re.S,
        )
    DOC.write_text(text, encoding="utf-8")
    print(f"docs/api.md: {len(paths)} paths written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())