@pytest.mark.asyncio
async def test_handle_story_illustrate_enqueues_image_job(session, wired_engine, monkeypatch):
    story = Story(title="T")
    session.add(story)
    session.commit()
    session.refresh(story)
    chapter = StoryChapter(title="Ch 1", story_id=story.id, content="a", image_paths=[])
    session.add(chapter)
    session.commit()
    session.refresh(chapter)

    def fake_checkpoint(self, preferred=None):
        return "checkpoint.safetensors"

    enqueue = AsyncMock(return_value=True)
    monkeypatch.setattr(
        "services.model_availability_service.ModelAvailabilityService.get_available_checkpoint",
        fake_checkpoint,
    )
    monkeypatch.setattr("services.job_queue.queue_manager.enqueue", enqueue)

    job_data = {
        "id": "job-4",
        "workflow": {"checkpoint": "checkpoint.safetensors"},
        "metadata": {"story_id": story.id, "chapter_id": chapter.id},
        "outputs": [{"role": "assistant", "content": "A misty castle on a cliff."}],
    }
    await wis._handle_story_illustrate(job_data)

    enqueue.assert_awaited_once()
    with Session(wired_engine) as check:
        img_job = check.exec(select(Job).where(Job.task_type == "image")).one()
        assert img_job.metadata_["workspace"] == "story"
        assert img_job.metadata_["story_id"] == story.id
        assert img_job.metadata_["chapter_id"] == chapter.id


