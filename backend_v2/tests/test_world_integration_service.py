@pytest.mark.asyncio
async def test_handle_story_image_appends_to_chapter(session, wired_engine):
    story = Story(title="T")
    session.add(story)
    session.commit()
    session.refresh(story)
    chapter = StoryChapter(title="Ch 1", story_id=story.id, content="a", image_paths=[])
    session.add(chapter)
    session.commit()
    session.refresh(chapter)

    job_data = {
        "id": "job-3",
        "metadata": {"chapter_id": chapter.id},
        "outputs": [{"relative_path": "2026/08/11/story.png"}],
    }
    await wis._handle_story_image(job_data)

    with Session(wired_engine) as check:
        ch = check.get(StoryChapter, chapter.id)
        assert ch.image_paths == ["2026/08/11/story.png"]

    # idempotent: second event does not duplicate
    await wis._handle_story_image(job_data)
    with Session(wired_engine) as check:
        ch = check.get(StoryChapter, chapter.id)
        assert ch.image_paths == ["2026/08/11/story.png"]


