# The handlers open their own Session(engine); point them at the test engine.
@pytest.fixture
def wired_engine(engine, monkeypatch):
    monkeypatch.setattr(wis, "engine", engine)
    return engine


def _seed_chat_with_character(session: Session) -> tuple[str, str]:
    char = Character(name="Aria")
    session.add(char)
    session.commit()
    session.refresh(char)
    chat = Chat(name="Test Chat", character_id=char.id)
    session.add(chat)
    session.commit()
    session.refresh(chat)
    return chat.id, char.id


