# ── _handle_chat_reply (message persistence on JOB_COMPLETED) ───────────────

@pytest.mark.asyncio
async def test_handle_chat_reply_persists_assistant_message(session, wired_engine):
    chat_id, _ = _seed_chat_with_character(session)

    job_data = {
        "id": "job-6",
        "metadata": {"chat_id": chat_id},
        "outputs": [{"role": "assistant", "content": "Hello back!"}],
    }
    await wis._handle_chat_reply(job_data)

    with Session(wired_engine) as check:
        msgs = check.exec(
            select(Message).where(Message.chat_id == chat_id).order_by(Message.created_at)
        ).all()
        assert len(msgs) == 1
        assert msgs[0].role == MessageRole.CHAR
        assert msgs[0].content == "Hello back!"


@pytest.mark.asyncio
async def test_handle_chat_reply_stores_tool_calls_transcript(session, wired_engine):
    chat_id, _ = _seed_chat_with_character(session)

    tool_calls = [{"id": "t1", "type": "function", "function": {"name": "generate_image"}}]
    job_data = {
        "id": "job-7",
        "metadata": {"chat_id": chat_id},
        "outputs": [{"role": "assistant", "content": "Let me show you.", "tool_calls": tool_calls}],
    }
    await wis._handle_chat_reply(job_data)

    with Session(wired_engine) as check:
        msg = check.exec(select(Message).where(Message.chat_id == chat_id)).one()
        assert msg.tool_calls == tool_calls
        assert msg.message_metadata == {"agentic": True}


