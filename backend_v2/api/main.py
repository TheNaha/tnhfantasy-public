async def _process_image_background(image_path: str, job_id: str):
    """
    Background post-processing hook after a job is marked completed.

    Thumbnails + blurhash are already generated by the asset reconciler in
    ``complete_when_ready`` (with the correct workspace partition); this hook
    only announces that the work is done so the UI can refresh.

    The announcement used to be a hand-built payload - ``{id, message,
    images_processed}`` - with no ``task_type`` and no ``progress``. The
    frontend's realtime handler drops any event payload without a
    ``task_type``, because a partial payload merged into the cached job drops
    ``task_type`` and ``provider_id`` and can move the status backwards. So
    the event that existed to refresh the UI could not refresh the UI, and
    every subscriber dropped it.

    It now carries the job's own representation, so it is a real job event
    like every other one.
    """
    try:
        from core.events import EventType, emit_job_event
        from services.job_service import JobService
        from infrastructure.database import get_session_sync

        session = get_session_sync()
        try:
            payload = await JobService(session).job_event_payload(job_id)
        finally:
            session.close()

        if not payload:
            return
        await emit_job_event(
            EventType.JOB_PROGRESS,
            {**payload, "message": "Thumbnails generated", "images_processed": True},
        )
    except Exception as e:
        logger.warning("image_processing_failed", job_id=job_id, path=image_path, error=str(e))


async def process_job(job_id: str, preferred_provider_id: str | None = None):
    """Thin wrapper that preserves stable patch points for tests and lifecycle wiring."""
    await execute_job(
        job_id,
        preferred_provider_id=preferred_provider_id,
        session_context_manager=get_session_context,
        process_image_background_fn=_process_image_background,
        get_timeout_fn=get_job_timeout,
        get_max_retries_fn=get_job_max_retries,
        get_retry_base_delay_fn=get_job_retry_base_delay,
        get_retry_max_delay_fn=get_job_retry_max_delay,
        get_stagger_delay_fn=get_llm_failover_stagger_delay,
    )


def _warn_if_multiple_processes() -> None:
    """Warn when more than one uvicorn process is configured.

    Multi-worker is now supported: job dispatch is safe under `FOR UPDATE
    SKIP LOCKED`, and WebSocket events cross processes via the Postgres
    NOTIFY bus (`tnhcomfy_job_events`) — each worker's `WebSocketManager`
    LISTENs on the channel and re-broadcasts to its local Socket.IO clients.

    Boot-time side effects (migrations, scheduler, asset migration, job
    recovery) still run N times but are advisory-locked and idempotent.
    """
    import multiprocessing

    requested = (
        os.getenv("COMFY_UVICORN_WORKERS", "").strip()
        or os.getenv("WEB_CONCURRENCY", "").strip()
    )
    if not requested:
        return
    try:
        workers = int(requested)
    except ValueError:
        logger.warning(
            "uvicorn_workers_unparseable",
            value=requested,
            note="expected an integer; treating as unset",
        )
        return
    if workers <= 1:
        return

    logger.warning(
        "multiple_uvicorn_processes",
        requested_workers=workers,
        pid=multiprocessing.current_process().pid,
        reason=(
            "Job dispatch is safe under FOR UPDATE SKIP LOCKED. WebSocket "
            "events cross processes via the Postgres NOTIFY bus "
            f"({CROSS_PROCESS_EVENT_CHANNEL}). Boot-time side effects "
            "(migrations, scheduler, recovery) run N times but are "
            "advisory-locked and idempotent."
        ),
    )


@asynccontextmanager
async def lifespan(app: FastAPI):
    """
    Application lifespan handler.
    Runs on startup and shutdown.
    """
    _warn_if_multiple_processes()
    configure_logging(
        os.getenv("COMFY_LOG_LEVEL", "INFO"),
        os.getenv("COMFY_LOG_FORMAT", "compact").strip().lower() == "json",
    )

    lifecycle_tasks = await startup_application(process_job, ws_manager)
    
    yield

    await shutdown_application(
        ws_manager,
        lifecycle_tasks["provider_monitor_task"],
        lifecycle_tasks["telemetry_task"],
        lifecycle_tasks["broadcast_task"],
        lifecycle_tasks.get("dispatch_listener_task"),
    )


