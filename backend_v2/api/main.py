# Logger for this module
logger = get_logger("main")


async def _process_image_background(image_path: str, job_id: str):
    """
    Background post-processing hook after a job is marked completed.

    Thumbnails + blurhash are already generated by the asset reconciler in
    ``complete_when_ready`` (with the correct workspace partition); this hook
    only emits the completion event so the UI can refresh.
    """
    try:
        # Emit event that image processing is complete
        from core.events import EventType, emit_job_event
        await emit_job_event(EventType.JOB_PROGRESS, {
            "id": job_id,
            "message": "Thumbnails generated",
            "images_processed": True
        })
    except Exception as e:
        logger.warning("image_processing_failed", job_id=job_id, path=image_path, error=str(e))


async def process_job(job_id: str, preferred_provider_id: str | None = None):
    """Thin wrapper that preserves stable patch points for tests and lifecycle wiring."""
    await execute_job(
        job_id,
        preferred_provider_id=preferred_provider_id,
        session_context_manager=get_session_context,
        call_image_provider_fn=_call_image_provider,
        call_llm_provider_fn=_call_llm_provider,
        process_image_background_fn=_process_image_background,
        get_timeout_fn=get_job_timeout,
        get_max_retries_fn=get_job_max_retries,
        get_retry_base_delay_fn=get_job_retry_base_delay,
        get_retry_max_delay_fn=get_job_retry_max_delay,
        get_stagger_delay_fn=get_llm_failover_stagger_delay,
    )


@asynccontextmanager
async def lifespan(app: FastAPI):
    """
    Application lifespan handler.
    Runs on startup and shutdown.
    """
    from api.deps import set_global_container_manager
    from services.container_manager import ContainerManager
    
    try:
        container_manager = ContainerManager()
    except Exception as e:
        logger.warning("container_manager_init_failed", error=str(e))
        container_manager = None
        
    app.state.container_manager = container_manager
    set_global_container_manager(container_manager)

    lifecycle_tasks = await startup_application(process_job, ws_manager)
    
    yield

    await shutdown_application(
        ws_manager,
        lifecycle_tasks["provider_monitor_task"],
        lifecycle_tasks["broadcast_task"],
    )


# Create FastAPI app
app = FastAPI(
    title="ComfyUI Modal Stack - Backend V2",
    description="Unified AI Fantasy Engine: PostgreSQL + pgvector World Vault (images, roleplay chat, stories) with a unified TaskEvent provider-protocol over Socket.IO/WebSocket.",
    version="2.0.0",
    lifespan=lifespan,
)


configure_app(app)

from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse

@app.exception_handler(RequestValidationError)
async def validation_exception_handler(request, exc):
    logger.error(f"Validation Error 422: {exc.errors()} - Body: {exc.body}")
    return JSONResponse(
        status_code=422,
        content={"detail": exc.errors(), "body": exc.body},
    )
